# -*- coding: utf-8 -*-
"""
Полнота молодняков высотой до 5 м по числу деревьев на гектар —
«Таблица для определения полноты молодняков до 5 м» (прислана Владом,
29.09.2026). Нужна для прил. 4–6 ведомостей текущих изменений: в полевых
карточках перевода полнота не пишется, а количество деревьев на 1 га есть.

Таблица задаёт нижние границы интервалов в тыс. шт/га: хвойные и
лиственные молодняки отдельно, лесные культуры и насаждения естественного
происхождения отдельно. Хвойный или лиственный молодняк — по главной
(первой в составе) породе.
"""
import re
from typing import Optional, Tuple

# (от, тыс. шт/га) -> полнота; последний интервал — «и больше».
KULTURY = {
    "hvoynye": [(2.0, 0.4), (2.7, 0.5), (3.4, 0.6), (4.2, 0.7), (5.0, 0.8), (5.9, 0.9), (6.8, 1.0)],
    "listvennye": [(2.0, 0.4), (2.7, 0.5), (3.9, 0.6), (5.2, 0.7), (6.4, 0.8), (7.7, 0.9), (8.9, 1.0)],
}
ESTESTVENNYE = {
    "hvoynye": [(4.0, 0.4), (4.6, 0.5), (5.6, 0.6), (6.6, 0.7), (7.6, 0.8), (8.6, 0.9), (9.6, 1.0)],
    "listvennye": [(5.0, 0.4), (5.7, 0.5), (6.9, 0.6), (8.2, 0.7), (9.4, 0.8), (10.7, 0.9), (11.9, 1.0)],
}
# Меньше первой строки таблицы — такую полноту ставим и помечаем «ниже
# таблицы», чтобы человек проверил.
NIZHE_TABLICY = 0.4

# Коды хвойных пород (как в составе: 7Е3С, 5рЕ4рС1рБ).
HVOYNYE = {"С", "Е", "Лц", "П", "Пх", "К", "Кд", "Т", "Ск", "Ек", "Сс"}


def glavnaya_poroda(sostav: str) -> str:
    """Код первой породы в составе: «7Е3С» -> «Е», «5рЕ4рС1рБ» -> «Е»."""
    m = re.match(r"\s*\d*\s*р?\s*([А-ЯЁ][а-яё]*)", str(sostav or ""))
    return m.group(1) if m else ""


def hvoynyy(sostav: str) -> bool:
    return glavnaya_poroda(sostav) in HVOYNYE


def po_kolichestvu(tys_na_ga: Optional[float], sostav: str, kultury: bool = True) -> Tuple[Optional[float], bool]:
    """(полнота, ниже таблицы?) по количеству деревьев в тыс. шт/га."""
    if tys_na_ga is None or tys_na_ga <= 0:
        return None, False
    table = (KULTURY if kultury else ESTESTVENNYE)["hvoynye" if hvoynyy(sostav) else "listvennye"]
    value = None
    for ot, p in table:
        if tys_na_ga >= ot - 1e-9:
            value = p
    if value is None:
        return NIZHE_TABLICY, True
    return value, False
