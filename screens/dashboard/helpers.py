from typing import Optional

# Роза ветров: переводим направление в градусах (0 = север, по часовой
# стрелке), которое отдаёт Open-Meteo, в короткое русское сокращение —
# так его удобнее показывать на узкой карточке, чем "273°".
_WIND_DIR_NAMES = (
    "С", "ССВ", "СВ", "ВСВ", "В", "ВЮВ", "ЮВ", "ЮЮВ",
    "Ю", "ЮЮЗ", "ЮЗ", "ЗЮЗ", "З", "ЗСЗ", "СЗ", "ССЗ",
)


def _wind_direction_to_text(degrees) -> Optional[str]:
    """Градусы направления ветра (0-360) -> короткое русское сокращение
    ("СЗ", "ЮВ" и т.п.). None, если данных нет или они некорректны."""
    if degrees is None:
        return None
    try:
        deg = float(degrees) % 360
    except (TypeError, ValueError):
        return None
    idx = int((deg + 11.25) // 22.5) % len(_WIND_DIR_NAMES)
    return _WIND_DIR_NAMES[idx]


def _compute_fire_danger(temperature, humidity) -> tuple[int, str]:
    """Оценивает класс пожарной опасности (1-5) по температуре (°C) и
    относительной влажности (%) — упрощённая эвристика (не официальная
    методика Нестерова, но даёт разумную "температуру" на дашборде без
    сложных многодневных расчётов):

        Класс 1 — до 15°C или высокая влажность  — "Малая пожароопасность"
        Класс 2 — 15-20°C, влажность 50-70%       — "Небольшая пожароопасность"
        Класс 3 — >20°C, влажность <50%           — "Средняя пожароопасность"
        Класс 4 — >25°C, влажность <40%           — "Высокая пожароопасность"
        Класс 5 — >30°C, влажность <30%           — "Чрезвычайная пожароопасность"

    Если температура или влажность неизвестны — возвращает класс 1
    (безопасное по умолчанию значение, чтобы не пугать лесничего
    ложной тревогой при сбое API)."""
    if temperature is None or humidity is None:
        return 1, "Малая пожароопасность"
    try:
        t = float(temperature)
        h = float(humidity)
    except (TypeError, ValueError):
        return 1, "Малая пожароопасность"

    if t > 30 and h < 30:
        return 5, "Чрезвычайная пожароопасность"
    if t > 25 and h < 40:
        return 4, "Высокая пожароопасность"
    if t > 20 and h < 50:
        return 3, "Средняя пожароопасность"
    if t >= 15 and h < 70:
        return 2, "Небольшая пожароопасность"
    return 1, "Малая пожароопасность"
