export default function SlovarButton() {
  const [open, setOpen] = useState(false);
  const [q, setQ] = useState("");
  const list = useMemo(() => {
    const s = q.trim().toLowerCase();
    return SLOVAR.filter(([t, d]) => !s || t.toLowerCase().includes(s) || d.toLowerCase().includes(s));
  }, [q]);
  return (
    <>
      <button
        type="button"
        title="Словарь сокращений и подсказки"
        onClick={() => setOpen(true)}
        style={{ height: 30, width: 30, borderRadius: 999, border: "1px solid #e5e2db", background: "#fff", color: "#1a4331", fontWeight: 800, cursor: "pointer" }}
      >
        ?
      </button>
      <Modal open={open} onClose={() => setOpen(false)} title="Словарь: что значат слова и сокращения" size="lg">
        <input
          autoFocus
          value={q}
          onChange={(e) => setQ(e.target.value)}
          placeholder="Найти слово…"
          className="w-full mb-3 bg-surface border border-border focus:border-pine rounded-[10px] px-3 h-10 text-[13.5px] text-ink outline-none"
        />
        <dl className="flex flex-col gap-2.5">
          {list.map(([t, d]) => (
            <div key={t}>
              <dt className="font-semibold text-ink text-[13.5px]">{t}</dt>
              <dd className="text-muted text-[13px]">{d}</dd>
            </div>
          ))}
        </dl>
        <p className="text-xs text-muted-2 mt-4">
          Подробно, с картинками —{" "}
          <a href="/guide/index.html" target="_blank" rel="noreferrer" className="underline text-pine">
            руководство по сайту и приложению
          </a>
          .
        </p>
      </Modal>
    </>
  );
}
